// =============================================================================
// FigForge — frame code generator. Emits the strongly-typed accessor layer:
//   • <Frame>.g.cs   — `public partial class LaunchPage : FigForgeFrame` with a
//                      [SerializeField] ref + typed property per frame-scoped element.
//   • FrameManager.g.cs — static accessors (FrameManager.LaunchPage), grouped by
//                      section as nested static classes.
//   • deterministic .cs.meta GUIDs so the generated prefab YAML can reference the
//     frame script BEFORE it compiles (one-pass import, no domain-reload wiring).
//
// This file is PURE generation (string in → string out) + the element→C# type map.
// The importer assembles the FrameModel from the manifest and writes the files +
// wires the [SerializeField] refs by fileID when it authors the frame prefab YAML.
// =============================================================================

using System;
using System.Collections.Generic;
using System.Text;

namespace FigForge
{
    /// <summary>One typed member of a generated frame: a child element surfaced as a
    /// serialized, strongly-typed accessor.</summary>
    internal struct FrameMember
    {
        public string identifier;  // case-preserved C# identifier, e.g. "button_default"
        public string csharpType;  // namespace-imported, e.g. "FigForgeButton" (generated files emit the usings)
        public string sourceName;  // manifest element id used to wire the generated field
        public string sourceType;  // manifest element type, e.g. GROUP or FRAME
        public string registryKey; // sanitized element name — runtime lookup key (e.g. Dialogs.X → Find(key))
        public string parentId;    // manifest parent id, used for generated container scopes
        public string scopeParentId;
        public bool exposeOnFrame;
        public bool isGroup;
        public string groupTypeName;

        /// <summary>Registry key + serialized-field stem. The property keeps any `@` escape,
        /// but the string key and backing field drop it: `@class` → key "class", field "_class".</summary>
        public string Key => (identifier ?? "").TrimStart('@');
        public string FieldName => "_" + Key;
    }

    /// <summary>One generated frame.</summary>
    internal struct FrameModel
    {
        public string className;   // case-preserved, e.g. "LaunchPage"
        public string screenKey;   // runtime FrameManager.Find key (object name or sanitized object name)
        public string section;     // enclosing section identifier, "" if none
        public string scriptGuid;  // deterministic 32-hex GUID for the generated .cs
        public bool isOverlay;     // a role=overlay layer → its FigForgeModals also emit global Dialogs.X accessors
        public List<FrameMember> members;
    }

    internal static class FrameCodeGen
    {
        public const string GeneratedNamespace = "FigForge.Generated";

        // ---- deterministic GUID (so prefab YAML can name the script pre-compile) -----
        public static string DeterministicGuid(string seed)
        {
            ulong h1 = Fnv("figforge-frame-" + seed);
            ulong h2 = Fnv(seed + "-frame-figforge");
            return h1.ToString("x16") + h2.ToString("x16"); // 32 hex chars
        }

        static ulong Fnv(string s)
        {
            unchecked
            {
                ulong h = 14695981039346656037UL;
                for (int i = 0; i < s.Length; i++) { h ^= s[i]; h *= 1099511628211UL; }
                return h;
            }
        }

        // ---- <Frame>.g.cs -------------------------------------------------------------
        public static string EmitFrameClass(FrameModel f)
        {
            var members = RootMembers(f); // top-level only — group children live in the group files

            var sb = new StringBuilder();
            sb.AppendLine("// <auto-generated> FigForge frame accessors — regenerated on import. Do not edit.");
            sb.AppendLine("// Add behaviour in a SEPARATE file: `public partial class " + f.className + " { ... }`.");
            sb.AppendLine("// Each Figma group is its own component (see the " + f.className + ".g folder); reach a");
            sb.AppendLine("// group's children through it, e.g. " + f.className + ".SomeGroup.someChild.");
            sb.AppendLine("// Show/hide anything from code: controls and groups have isVisible / SetVisible(bool).");
            sb.AppendLine("// Add click listeners in `public override void OnBind()` for hidden-at-start frames.");
            sb.AppendLine("using FigForge;");
            sb.AppendLine("using TMPro;");
            sb.AppendLine("using UnityEngine;");
            sb.AppendLine("using UnityEngine.UI;");
            sb.AppendLine();
            sb.AppendLine("namespace " + GeneratedNamespace);
            sb.AppendLine("{");
            sb.AppendLine("    public partial class " + f.className + " : FigForgeFrame");
            sb.AppendLine("    {");

            EmitAccessorsAndFields(sb, members);

            // Navigation key — registry key for Frames.Guard<...>; never change it by hand.
            sb.AppendLine();
            sb.AppendLine("        // ──────── Navigation key (internal; do not modify) ────────");
            sb.AppendLine("        // `__`-prefixed by convention so it can't collide with an element-named member.");
            sb.AppendLine("        public const string __ScreenKey = \"" + Escape(f.screenKey) + "\";");

            sb.AppendLine();
            sb.AppendLine("        // ──────── Wiring (called by the importer; don't call by hand) ────────");
            sb.AppendLine("        public override void __WireFrame(FigForgeScreen reg)");
            EmitWireBody(sb, members);

            sb.AppendLine("    }");
            sb.AppendLine("}");
            return sb.ToString();
        }

        // One component per Figma group, generated into the <Frame>.g folder. It sits ON the
        // group's GameObject (a FigForgeFrameElement subclass) and holds that group's child
        // refs — so they appear on the group's inspector instead of crowding the frame. The
        // frame exposes the group itself as a typed accessor; isVisible / SetVisible /
        // RectTransform come from the FigForgeFrameElement base.
        public static string EmitGroupClass(FrameModel f, FrameMember group)
        {
            var children = GroupChildren(f, group);

            var sb = new StringBuilder();
            sb.AppendLine("// <auto-generated> FigForge group accessors for '" + group.identifier + "' (in " + f.className + ") — regenerated on import. Do not edit.");
            sb.AppendLine("// Add behaviour in a SEPARATE file: `public partial class " + group.groupTypeName + " { ... }`.");
            sb.AppendLine("using FigForge;");
            sb.AppendLine("using TMPro;");
            sb.AppendLine("using UnityEngine;");
            sb.AppendLine("using UnityEngine.UI;");
            sb.AppendLine();
            sb.AppendLine("namespace " + GeneratedNamespace);
            sb.AppendLine("{");
            sb.AppendLine("    public partial class " + group.groupTypeName + " : FigForgeFrameElement");
            sb.AppendLine("    {");

            EmitAccessorsAndFields(sb, children);

            sb.AppendLine();
            sb.AppendLine("        // ──────── Wiring (called by the importer; don't call by hand) ────────");
            sb.AppendLine("        public override void __WireGroup(FigForgeScreen reg)");
            EmitWireBody(sb, children);

            sb.AppendLine("    }");
            sb.AppendLine("}");
            return sb.ToString();
        }

        // Shared body for the frame and each group: public accessors first (the surface devs
        // reach for), then the [SerializeField] backing fields. Every member — leaf control or
        // child group — is reached the same way: a lazy, null-safe __Get against the registry.
        static void EmitAccessorsAndFields(StringBuilder sb, List<FrameMember> members)
        {
            if (members.Count == 0) return;
            sb.AppendLine();
            sb.AppendLine("        // ──────── Accessors ────────");
            foreach (var m in members)
                sb.AppendLine("        public " + m.csharpType + " " + m.identifier + " => __Get(ref " + m.FieldName + ", \"" + Escape(m.Key) + "\");");
            sb.AppendLine();
            sb.AppendLine("        // ──────── Element references (serialized; auto-wired on import) ────────");
            foreach (var m in members)
                sb.AppendLine("        [SerializeField] " + m.csharpType + " " + m.FieldName + ";");
        }

        static void EmitWireBody(StringBuilder sb, List<FrameMember> members)
        {
            sb.AppendLine("        {");
            sb.AppendLine("            if (reg == null) return;");
            foreach (var m in members)
                sb.AppendLine("            " + m.FieldName + " = reg.Get<" + m.csharpType + ">(\"" + m.Key + "\");");
            sb.AppendLine("        }");
        }

        // Frame-level members (no scope parent) → emitted on the frame. The rest belong to a
        // group and are emitted in that group's component instead.
        static List<FrameMember> RootMembers(FrameModel f)
        {
            var list = new List<FrameMember>();
            if (f.members != null)
                foreach (var m in f.members)
                    if (string.IsNullOrEmpty(m.scopeParentId)) list.Add(m);
            return list;
        }

        static List<FrameMember> GroupChildren(FrameModel f, FrameMember group)
        {
            var list = new List<FrameMember>();
            if (f.members != null)
                foreach (var m in f.members)
                    if (m.scopeParentId == group.sourceName) list.Add(m);
            return list;
        }

        // ---- FrameManager.g.cs --------------------------------------------------------
        public static string EmitFrameManager(IList<FrameModel> frames)
        {
            var sb = new StringBuilder();
            sb.AppendLine("// <auto-generated> FigForge static frame accessors — regenerated on import. Do not edit.");
            sb.AppendLine("using FigForge;");
            sb.AppendLine("namespace " + GeneratedNamespace);
            sb.AppendLine("{");
            sb.AppendLine("    public static partial class Frames");
            sb.AppendLine("    {");

            foreach (var f in frames)
                if (string.IsNullOrEmpty(f.section))
                    sb.AppendLine("        " + Accessor(f));

            var sections = new SortedSet<string>(StringComparer.Ordinal);
            foreach (var f in frames) if (!string.IsNullOrEmpty(f.section)) sections.Add(f.section);
            foreach (var sec in sections)
            {
                sb.AppendLine();
                sb.AppendLine("        public static partial class " + sec);
                sb.AppendLine("        {");
                foreach (var f in frames)
                    if (f.section == sec)
                        sb.AppendLine("            " + Accessor(f));
                sb.AppendLine("        }");
            }

            sb.AppendLine("    }");
            sb.AppendLine("}");
            return sb.ToString();
        }

        // A single-frame `Frames` partial — one file per frame so page-by-page imports
        // don't clobber each other's accessors. Sections become a partial nested static
        // class (multiple frames in a section each contribute to it).
        public static string EmitFrameManagerForFrame(FrameModel f)
        {
            var sb = new StringBuilder();
            sb.AppendLine("// <auto-generated> FigForge frame accessor — regenerated on import. Do not edit.");
            sb.AppendLine("using FigForge;");
            sb.AppendLine("namespace " + GeneratedNamespace);
            sb.AppendLine("{");
            sb.AppendLine("    public static partial class Frames");
            sb.AppendLine("    {");
            if (string.IsNullOrEmpty(f.section))
            {
                sb.AppendLine("        " + Accessor(f));
            }
            else
            {
                sb.AppendLine("        public static partial class " + f.section);
                sb.AppendLine("        {");
                sb.AppendLine("            " + Accessor(f));
                sb.AppendLine("        }");
            }
            sb.AppendLine("    }");
            sb.AppendLine("}");
            return sb.ToString();
        }

        // The fixed `Frames` core — navigation that proxies the internal FrameManager.
        // Written once (Frames.Core.g.cs); per-frame files add the typed accessors.
        public static string EmitFramesCore()
        {
            var sb = new StringBuilder();
            sb.AppendLine("// <auto-generated> FigForge frame navigation — regenerated on import. Do not edit.");
            sb.AppendLine("using FigForge;");
            sb.AppendLine("namespace " + GeneratedNamespace);
            sb.AppendLine("{");
            sb.AppendLine("    // The single public entry point. Wraps the internal FrameManager engine.");
            sb.AppendLine("    public static partial class Frames");
            sb.AppendLine("    {");
            sb.AppendLine("        // The frame currently shown (null before any Show / in edit mode).");
            sb.AppendLine("        public static FigForgeFrame Current");
            sb.AppendLine("            => FrameManager.Resolve()?.Current;");
            sb.AppendLine();
            sb.AppendLine("        // Typed + null-safe navigation: Frames.Show(Frames.Settings). (Or Frames.Settings.Show().)");
            sb.AppendLine("        public static void Show(FigForgeFrame frame) { if (frame != null) frame.Show(); }");
            sb.AppendLine();
            sb.AppendLine("        // ---- navigation guards (preconditions) -------------------------------");
            sb.AppendLine("        // Gate entry to a screen with real C#. Register once at runtime, e.g. in a");
            sb.AppendLine("        // bootstrap component's Start():");
            sb.AppendLine("        //   Frames.Guard<Checkout>(ctx => PlayerState.HasProfile");
            sb.AppendLine("        //       ? FigForge.NavDecision.Allow()");
            sb.AppendLine("        //       : FigForge.NavDecision.BlockDialog(Frames.CompleteProfileDialog));");
            sb.AppendLine("        public static void Guard<TFrame>(NavGuard guard) where TFrame : FigForgeFrame");
            sb.AppendLine("            => FigForgeNavigation.AddGuard<TFrame>(guard);");
            sb.AppendLine();
            sb.AppendLine("        // Guard a specific screen instance: Frames.Guard(Frames.Checkout, ctx => ...).");
            sb.AppendLine("        public static void Guard(FigForgeFrame frame, NavGuard guard)");
            sb.AppendLine("            => FigForgeNavigation.AddGuard(frame, guard);");
            sb.AppendLine();
            sb.AppendLine("        // Guard EVERY navigation (auth, feature flags). Runs before per-screen guards.");
            sb.AppendLine("        public static void GuardAll(NavGuard guard)");
            sb.AppendLine("            => FigForgeNavigation.AddGlobalGuard(guard);");
            sb.AppendLine();
            sb.AppendLine("        // React to a blocked navigation in code (or drop a FigForgeNavBlockedHandler component).");
            sb.AppendLine("        public static void OnBlocked(System.Action<NavContext, NavDecision> handler)");
            sb.AppendLine("            => FigForgeNavigation.AddBlockedHandler(handler);");
            sb.AppendLine();
            sb.AppendLine("        // Ensure every registered frame has run OnBind(), including inactive pages.");
            sb.AppendLine("        public static void BindAll() { FrameManager.Resolve()?.BindAll(); }");
            sb.AppendLine();
            sb.AppendLine("        // Run an action after a delay, chainable: Frames.After(1f, A).After(2f, B).");
            sb.AppendLine("        public static DelayChain After(float seconds, System.Action action)");
            sb.AppendLine("            => new DelayChain(FrameManager.Resolve()).After(seconds, action);");
            sb.AppendLine();
            sb.AppendLine("        public sealed class DelayChain");
            sb.AppendLine("        {");
            sb.AppendLine("            struct Step");
            sb.AppendLine("            {");
            sb.AppendLine("                public float seconds;");
            sb.AppendLine("                public System.Action action;");
            sb.AppendLine("                public Step(float seconds, System.Action action) { this.seconds = seconds; this.action = action; }");
            sb.AppendLine("            }");
            sb.AppendLine();
            sb.AppendLine("            readonly FrameManager _manager;");
            sb.AppendLine("            readonly System.Collections.Generic.Queue<Step> _steps = new System.Collections.Generic.Queue<Step>();");
            sb.AppendLine("            UnityEngine.Coroutine _coroutine;");
            sb.AppendLine();
            sb.AppendLine("            internal DelayChain(FrameManager manager) { _manager = manager; }");
            sb.AppendLine("            public bool IsRunning => _coroutine != null;");
            sb.AppendLine();
            sb.AppendLine("            public DelayChain After(float seconds, System.Action action)");
            sb.AppendLine("            {");
            sb.AppendLine("                if (action == null) return this;");
            sb.AppendLine("                _steps.Enqueue(new Step(seconds, action));");
            sb.AppendLine("                if (_manager != null && _coroutine == null)");
            sb.AppendLine("                    _coroutine = _manager.StartCoroutine(Run());");
            sb.AppendLine("                return this;");
            sb.AppendLine("            }");
            sb.AppendLine();
            sb.AppendLine("            public void Cancel()");
            sb.AppendLine("            {");
            sb.AppendLine("                _steps.Clear();");
            sb.AppendLine("                if (_manager != null && _coroutine != null)");
            sb.AppendLine("                    _manager.StopCoroutine(_coroutine);");
            sb.AppendLine("                _coroutine = null;");
            sb.AppendLine("            }");
            sb.AppendLine();
            sb.AppendLine("            System.Collections.IEnumerator Run()");
            sb.AppendLine("            {");
            sb.AppendLine("                while (_steps.Count > 0)");
            sb.AppendLine("                {");
            sb.AppendLine("                    var step = _steps.Dequeue();");
            sb.AppendLine("                    if (step.seconds > 0f) yield return new UnityEngine.WaitForSeconds(step.seconds);");
            sb.AppendLine("                    try { step.action(); }");
            sb.AppendLine("                    catch (System.Exception e) { UnityEngine.Debug.LogException(e); }");
            sb.AppendLine("                }");
            sb.AppendLine("                _coroutine = null;");
            sb.AppendLine("            }");
            sb.AppendLine("        }");
            sb.AppendLine("    }");
            sb.AppendLine("}");
            return sb.ToString();
        }

        static string Accessor(FrameModel f)
        {
            // Emitted INSIDE namespace FigForge.Generated, so the frame type is unqualified;
            // the manager is the package's FrameManager (via `using FigForge;`).
            return "public static " + f.className + " " + f.className
                 + " => FrameManager.Resolve()?.Find(\"" + Escape(f.screenKey) + "\") as " + f.className + ";";
        }

        // ---- global dialog accessors (overlay layers) ---------------------------------
        // Every FigForgeModal in a role=overlay frame also surfaces as a strongly-typed,
        // string-free `Dialogs.<Name>` — resolved through the lazy global FigForgeDialogHost,
        // so it works on any screen (shell or not). One file per overlay frame, mirroring
        // Frames.<Frame>.g.cs; the fixed helpers live in Dialogs.Core.g.cs.
        public static bool HasDialogs(FrameModel f)
        {
            if (f.members == null) return false;
            foreach (var m in f.members)
                if (m.csharpType == "FigForgeModal") return true;
            return false;
        }

        public static string EmitDialogsForFrame(FrameModel f)
        {
            var sb = new StringBuilder();
            sb.AppendLine("// <auto-generated> FigForge global dialog accessors — regenerated on import. Do not edit.");
            sb.AppendLine("// Strongly typed, no strings: `Dialogs." + f.className + "Dialog.Open();` from anywhere.");
            sb.AppendLine("using FigForge;");
            sb.AppendLine("namespace " + GeneratedNamespace);
            sb.AppendLine("{");
            sb.AppendLine("    public static partial class Dialogs");
            sb.AppendLine("    {");
            if (f.members != null)
                foreach (var m in f.members)
                    if (m.csharpType == "FigForgeModal")
                        sb.AppendLine("        public static FigForgeModal " + m.identifier
                                    + " => FigForgeDialogHost.Resolve()?.Find(\"" + Escape(m.registryKey) + "\");");
            sb.AppendLine("    }");
            sb.AppendLine("}");
            return sb.ToString();
        }

