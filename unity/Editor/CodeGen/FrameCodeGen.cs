        // ---- generated .cs.meta + asmdef ----------------------------------------------
        public static string EmitScriptMeta(string guid)
        {
            return "fileFormatVersion: 2\n"
                 + "guid: " + guid + "\n"
                 + "MonoImporter:\n"
                 + "  externalObjects: {}\n"
                 + "  serializedVersion: 2\n"
                 + "  defaultReferences: []\n"
                 + "  executionOrder: 0\n"
                 + "  icon: {instanceID: 0}\n"
                 + "  userData: \n"
                 + "  assetBundleName: \n"
                 + "  assetBundleVariant: \n";
        }

        public static string EmitAsmdef()
        {
            return "{\n"
                 + "  \"name\": \"FigForge.Generated\",\n"
                 + "  \"rootNamespace\": \"FigForge.Generated\",\n"
                 + "  \"references\": [\n"
                 + "    \"FigForge.Runtime\",\n"
                 + "    \"Unity.TextMeshPro\",\n"
                 + "    \"UnityEngine.UI\"\n"
                 + "  ],\n"
                 + "  \"autoReferenced\": true\n"
                 + "}\n";
        }

        // ---- element → C# accessor type ----------------------------------------------
        public static string CSharpType(ElementData e)
        {
            var c = e != null ? e.canonical : null;
            if (c != null && !string.IsNullOrEmpty(c.kind))
            {
                switch (c.kind)
                {
                    case "button": return "FigForgeButton";
                    case "toggle":
                    case "radio": return "FigForgeToggle";
                    case "switch": return "FigForgeSwitch";
                    case "dropdown": return "FigForgeDropdown";
                    case "input": return "FigForgeInputField";
                    case "stepper": return "FigForgeStepper";
                    case "slider": return "FigForgeSlider";
                    case "progress": return "FigForgeProgress";
                    case "list": return "FigForgeList";
                    case "table": return "FigForgeTable";
                    case "modal": return "FigForgeModal";
                    case "toast": return "FigForgeToastHost";
                }
            }
            if (e != null && (e.type == "TEXT" || (e.components != null && e.components.Contains("TextMeshProUGUI"))))
                return "TMP_Text";
            if (e != null && e.components != null && e.components.Contains("Image"))
                return "Image";
            return "RectTransform"; // plain container / unknown
        }

        static string Escape(string s) => (s ?? "").Replace("\\", "\\\\").Replace("\"", "\\\"");
    }
