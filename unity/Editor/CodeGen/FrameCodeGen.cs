        // ---- element → C# accessor type ----------------------------------------------
        public static string CSharpType(ElementData e)
        {
            var c = e != null ? e.canonical : null;
            if (c != null && !string.IsNullOrEmpty(c.kind))
            {
                switch (c.kind)
                {
                    case "button": return "FigForge.FigForgeButton";
                    case "toggle":
                    case "radio": return "FigForge.FigForgeToggle";
                    case "switch": return "FigForge.FigForgeSwitch";
                    case "dropdown": return "FigForge.FigForgeDropdown";
                    case "input": return "FigForge.FigForgeInputField";
                    case "stepper": return "FigForge.FigForgeStepper";
                    case "slider": return "FigForge.FigForgeSlider";
                    case "progress": return "FigForge.FigForgeProgress";
                    case "list": return "FigForge.FigForgeList";
                    case "table": return "FigForge.FigForgeTable";
                    case "modal": return "FigForge.FigForgeModal";
                    case "toast": return "FigForge.FigForgeToastHost";
                }
            }
            if (e != null && (e.type == "TEXT" || (e.components != null && e.components.Contains("TextMeshProUGUI"))))
                return "TMPro.TMP_Text";
            if (e != null && e.components != null && e.components.Contains("Image"))
                return "UnityEngine.UI.Image";
            return "UnityEngine.RectTransform"; // plain container / unknown
        }

        static string Escape(string s) => (s ?? "").Replace("\\", "\\\\").Replace("\"", "\\\"");
    }
